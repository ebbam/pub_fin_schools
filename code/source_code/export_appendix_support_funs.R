# ============================================================================
# APPEND FILE TO APPENDIX FUNCTION
# ============================================================================

append_file_to_appendix <- function(filepath, float_barrier = FALSE, title = NULL) {
  if (!BUILDING_APPENDIX) return(invisible(NULL))
  
  # Check if file exists
  if (!file.exists(filepath)) {
    warning("File not found: ", filepath)
    return(invisible(NULL))
  }
  
  lines <- character()
  
  # Add title if provided
  if (!is.null(title)) {
    # Convert markdown title to LaTeX
    latex_title <- title
    if (grepl("^##\\s", title)) {
      latex_title <- gsub("^##\\s*(.+)$", "\\\\subsection{\\1}", title)
    } else if (grepl("^#\\s", title)) {
      latex_title <- gsub("^#\\s*(.+)$", "\\\\section{\\1}", title)
    }
    lines <- c(lines, "", latex_title, "")
  }
  
  # Read the file content
  file_content <- readLines(filepath, warn = FALSE)
  lines <- c(lines, "", file_content, "")
  
  # Add float barrier if requested
  if (float_barrier) {
    lines <- c(lines, "", "\\FloatBarrier", "")
  }
  
  # Append to local appendix
  write(lines, file = here("output/tex", appendix_file), append = TRUE)
  
  # Append to Dropbox appendix
  write(lines, file = file.path(DROPBOX_PAPER_PATH, "si_docs", appendix_file), append = TRUE)
  
  cat("Appended file to appendix:", filepath, "\n")
  if (!is.null(title)) cat("  with title:", title, "\n")
}
