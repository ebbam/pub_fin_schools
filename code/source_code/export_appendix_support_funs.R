# Function to export table to both local and Dropbox
export_table <- function(table_tex, filename) {
  # Write to local
  cat(table_tex, file = here("output/tex", filename))
  
  # Write to Dropbox
  cat(table_tex, file = file.path(DROPBOX_PAPER_PATH, "tables", filename))
  
  #cat("Exported table:", filename, "\n")
}

# Function to export figure to both local and Dropbox
export_figure <- function(plot_obj, filename, dpi = 300, width = 8, height = 8, beamer = FALSE) {
  
  if(beamer){
    filename <- paste0(
      tools::file_path_sans_ext(filename),
      "_beamer.pdf"
    )
  }
  # Save to local
  ggsave(
    here("output/figures", filename),
    plot = plot_obj,
    width = width,
    height = height,
    dpi = dpi)
  
  # Save to Dropbox
  ggsave(
    file.path(DROPBOX_PAPER_PATH, "figures", filename),
    plot = plot_obj,
    width = width,
    height = height,
    dpi = dpi)
  
  #cat("Exported figure:", filename, "\n")
}

# ============================================================================
# MODIFIED APPEND_TO_APPENDIX FUNCTION - EXPORTS TO DROPBOX
# ============================================================================

append_to_appendix <- function(title, description_lines, float_barrier = TRUE, label = NULL) {
  if (!BUILDING_APPENDIX) return(invisible(NULL))
  
  chunk_label <- knitr::opts_current$get("label")
  
  # Convert markdown title to LaTeX
  # "## Title" -> "\subsection{Title}"
  # "# Title" -> "\section{Title}"
  latex_title <- title
  if (grepl("^##\\s", title)) {
    latex_title <- gsub("^##\\s*(.+)$", "\\\\subsection{\\1}", title)
  } else if (grepl("^#\\s", title)) {
    latex_title <- gsub("^#\\s*(.+)$", "\\\\section{\\1}", title)
  }
  
  # Add label if provided
  if (!is.null(label)) {
    latex_title <- paste0(latex_title, "\n\\label{", label, "}")
  }
  
  lines <- c(
    "",
    latex_title,
    "",
    description_lines,
    "",
    paste0("% Content from chunk: ", chunk_label),  
    "% (Generated by regressions.qmd)",
    ""
  )
  
  if (float_barrier) {
    lines <- c(lines, "\\FloatBarrier", "")
  }
  
  # Append to local file
  write(lines, file = here("output/tex", appendix_file), append = TRUE)
  
  # Append to Dropbox file
  write(lines, file = file.path(DROPBOX_PAPER_PATH, "si_docs", appendix_file), append = TRUE)
}

# Alternative function: append table output directly to appendix
append_table_to_appendix <- function(table_tex, landscape = FALSE) {
  if (!BUILDING_APPENDIX) return(invisible(NULL))
  
  if(landscape){
    lines <- c("\\begin{landscape}", "", table_tex, "", "\\end{landscape}")
  }else{
    lines <- c("", table_tex, "")
  }
  
  # Append to local
  write(lines, file = here("output/tex", appendix_file), append = TRUE)
  
  # Append to Dropbox
  write(lines, file = file.path(DROPBOX_PAPER_PATH, "si_docs", appendix_file), append = TRUE)
}

