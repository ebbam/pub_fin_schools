# ============================================================================
# APPEND FIGURE TO APPENDIX FUNCTION
# ============================================================================

append_figure_to_appendix <- function(plot_obj, filename, caption, label, width = "\\textwidth", fig_width = 8,            # Actual figure width in inches
                                      fig_height = 8, dpi = 300) {
  if (!BUILDING_APPENDIX) return(invisible(NULL))
  
  # Save figure to Dropbox
  fig_path <- file.path(DROPBOX_PAPER_PATH, "si_docs", filename)
  ggsave(fig_path, plot_obj, width = fig_width, height = fig_height)
  
  # Also save to local output folder (for backup)
  ggsave(here("output/figures", filename), plot_obj, width = fig_width, height = fig_height, dpi = dpi)
  
  # Add LaTeX code to appendix
  fig_latex <- c(
    "",
    "\\begin{figure}[htbp]",
    "  \\centering",
    paste0("  \\includegraphics[width=", width, "]{si_docs/", filename, "}"),
    #paste0("  \\caption{", caption, "}"),
    paste0("  \\label{", label, "}"),
    "\\end{figure}",
    "",
    "\\FloatBarrier",
    ""
  )
  
  append_table_to_appendix(paste(fig_latex, collapse = "\n"))
  
  cat("Appended figure to appendix:", filename, "\n")
}

